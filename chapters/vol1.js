  <p>两个人的净资产都是 100 万元，处境可能完全不同：一个人的 100 万元全在自住房里，另一个人有 30 万元活期存款。前者纸面相等，遇到急需用钱时却可能周转不动。所以看资产要分流动性——能多快、以多大代价变成现金。现金和活期存款流动性最高，房产变现慢且交易成本高，某些长期安排更是中途取出会受损失。</p>
