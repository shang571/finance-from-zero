  <p>能被分散掉的那部分，来自公司特有、彼此无关的扰动：一次产品失误、一位关键人员变动、一场局部事故。把它们放在一起，各自的意外互相抵消，这就是非系统性风险。另一部分来自共同因素——经济周期、利率变化、通货膨胀，它们几乎同时影响所有资产，无论怎么组合都无法消除，这就是系统性风险。市场愿意补偿的，是后一种。</p>

