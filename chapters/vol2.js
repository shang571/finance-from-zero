  <p>资产负债表的基本布局，是把会计等式的两边并排呈现：一侧列资产，另一侧列负债和所有者权益，两侧总计相等。资产这边按流动性从高到低排列，越靠近顶部越容易变成现金；权益那边则按偿还的紧迫程度安排。理解了这个排列逻辑，读表时就不必逐行死记，顺着结构的方向看下去即可。</p>
