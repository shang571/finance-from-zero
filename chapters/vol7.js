  <p>传统上央行有三件主要工具。公开市场操作是在金融市场上买卖证券，直接吞吐基础货币，日常使用最频繁；法定存款准备金率规定商业银行必须缴存的资金比例，调整它会影响银行可贷资金与货币乘数；再贴现与再贷款则是央行对商业银行的资金支持，兼有最后贷款人职能。近年来许多央行更重视价格型工具，通过政策利率引导货币市场利率，再传导到信贷与债券市场。数量型工具影响的是"有多少钱"，价格型工具影响的是"钱有多贵"，二者最终都会作用到借贷成本上。</p>

