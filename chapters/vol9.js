  <p>仓位管理的起点不是看哪个机会更好，而是先回答一个不太舒服的问题：如果判断错了，愿意损失多少？把这个上限写成总资金的一个固定比例，就是风险预算。假设总资金 10 万元，规定单笔最大亏损不超过总资金的 1%，即 1000 元；若按买入价的 8% 设定止损距离，那么每单位仓位的风险是买入价的 8%，可承受的仓位金额约为 1000 ÷ 8% = 1.25 万元，占总资金 12.5%。数字随假设而变，思路是固定的：先确定能亏多少，再反推能承担多大的仓位。</p>
