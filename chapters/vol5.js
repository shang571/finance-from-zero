  <p>这个演示故意用整数假设，只为说明方向：费率是确定的拖累，持有时间越长，拖累被复利放大得越明显。它提醒我们，比较基金时应把费率放在与历史业绩同等重要的位置。当然，低费率不是唯一标准，跟踪质量与服务能力同样要紧；只是别让看不见的小数字，悄悄改写长期结果。</p>

