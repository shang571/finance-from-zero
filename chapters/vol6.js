  <p>使用 WACC 还要记住两条边界。其一，只有项目风险与公司现有业务相近时才可直接套用，风险明显不同的项目应调整折现率；其二，WACC 不是越低越好——靠高杠杆压低数字的同时，也抬高了财务困境的概率。资本结构的选择，是在税盾收益与风险成本之间权衡。</p>

